    private void btnTimKiemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimKiemActionPerformed

String tuKhoa = txtTimKiem.getText().trim();

if (tuKhoa.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Vui long nhap ten hoac so dien thoai can tim!"
    );
    return;
}

// Goi DAO de tim kiem khach hang
quanlyvatlieuxaydung.dao.KhachHangDAO dao =
        new quanlyvatlieuxaydung.dao.KhachHangDAO();

java.util.List<Object[]> danhSach =
        dao.timKiemKhachHang(tuKhoa);

// Xoa du lieu cu tren bang
javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblKhachHang.getModel();

model.setRowCount(0);

// Dua ket qua tim kiem vao bang
for (Object[] khachHang : danhSach) {
    model.addRow(khachHang);
}

if (danhSach.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Khong tim thay khach hang phu hop!"
    );
}

    }//GEN-LAST:event_btnTimKiemActionPerformed
