    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        String tenKH = jTextField1.getText().trim();
    String sdt = jTextField2.getText().trim();
    String diaChi = jTextField3.getText().trim();

    if (tenKH.isEmpty() || sdt.isEmpty() || diaChi.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vui long nhap day du thong tin khach hang!"
        );
        return;
    }

    quanlyvatlieuxaydung.dao.KhachHangDAO dao =
            new quanlyvatlieuxaydung.dao.KhachHangDAO();

    boolean ketQua = dao.themKhachHang(tenKH, sdt, diaChi);

    if (ketQua) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Them khach hang thanh cong!"
        );

        taiDanhSachKhachHang();

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Them khach hang that bai!"
        );
    }
    }//GEN-LAST:event_btnThemActionPerformed
