    private void tblKhachHangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblKhachHangMouseClicked
        int selectedRow = tblKhachHang.getSelectedRow();

        if (selectedRow >= 0) {
         String tenKH = tblKhachHang.getValueAt(selectedRow, 1).toString();
        String sdt = tblKhachHang.getValueAt(selectedRow, 2).toString();
        String diaChi = tblKhachHang.getValueAt(selectedRow, 3).toString();

        jTextField1.setText(tenKH);
        jTextField2.setText(sdt);
        jTextField3.setText(diaChi);
        }
    }//GEN-LAST:event_tblKhachHangMouseClicked

    private void btnSuaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnSuaMouseClicked

    int selectedRow = tblKhachHang.getSelectedRow();

    if (selectedRow < 0) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Vui long chon khach hang can sua trong bang!"
    );
    return;
    }

// Lay ma khach hang tu cot dau tien
    int maKH = Integer.parseInt(
        tblKhachHang.getValueAt(selectedRow, 0).toString()
    );

// Lay thong tin moi tu cac o nhap
    String tenKH = jTextField1.getText().trim();
    String sdt = jTextField2.getText().trim();
    String diaChi = jTextField3.getText().trim();

// Kiem tra thong tin
    if (tenKH.isEmpty() || sdt.isEmpty() || diaChi.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Vui long nhap day du thong tin!"
    );
    return;
    }

// Goi DAO de cap nhat database
    quanlyvatlieuxaydung.dao.KhachHangDAO dao =
        new quanlyvatlieuxaydung.dao.KhachHangDAO();

    boolean ketQua = dao.suaKhachHang(maKH, tenKH, sdt, diaChi);

    if (ketQua) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Cap nhat khach hang thanh cong!"
    );

    taiDanhSachKhachHang();

    jTextField1.setText("");
    jTextField2.setText("");
    jTextField3.setText("");
    }              else {
            javax.swing.JOptionPane.showMessageDialog(
            this,
            "Cap nhat khach hang that bai!"
            );
        }
    }//GEN-LAST:event_btnSuaMouseClicked

