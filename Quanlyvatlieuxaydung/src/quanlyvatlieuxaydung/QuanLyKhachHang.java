    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed

    int selectedRow = tblKhachHang.getSelectedRow();

    if (selectedRow < 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Vui long chon khach hang can xoa trong bang!"
        );
        return;
    }

    // Lay ma khach hang tu cot dau tien
    int maKH = Integer.parseInt(
            tblKhachHang.getValueAt(selectedRow, 0).toString()
    );

    // Xac nhan truoc khi xoa
    int xacNhan = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Ban co chac chan muon xoa khach hang nay?",
            "Xac nhan xoa",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (xacNhan != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    // Goi DAO de xoa khach hang
    quanlyvatlieuxaydung.dao.KhachHangDAO dao =
            new quanlyvatlieuxaydung.dao.KhachHangDAO();

    boolean ketQua = dao.xoaKhachHang(maKH);

    if (ketQua) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Xoa khach hang thanh cong!"
        );

        // Tai lai bang sau khi xoa
        taiDanhSachKhachHang();

        // Xoa noi dung cac o nhap
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Xoa khach hang that bai!"
        );
    }

    }//GEN-LAST:event_btnXoaActionPerformed
